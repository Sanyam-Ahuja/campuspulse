export function generateInitialTelemetry(): NetworkTelemetryPoint[] {
  const points: NetworkTelemetryPoint[] = [];
  const now = Date.now();
  for (let i = 20; i >= 0; i--) {
    const timestamp = now - i * 4000;
    const date = new Date(timestamp);
    const time = `${date.getMinutes().toString().padStart(2, '0')}:${date.getSeconds().toString().padStart(2, '0')}`;
    const jitter = Math.sin(i * 0.8) * 3;
    points.push({
      time,
      timestamp,
      latencyMs: Math.round(14 + jitter),
      packetLossPct: parseFloat(Math.max(0, 0.05 + Math.sin(i * 0.5) * 0.04).toFixed(2)),
      throughputGbps: parseFloat((38.4 + Math.cos(i * 0.6) * 4.2).toFixed(1)),
      jitterMs: parseFloat((1.8 + Math.abs(Math.sin(i * 0.4)) * 1.2).toFixed(1)),
    });
  }
  return points;
}
